/**
 * productModel.ts — the product record shared by the admin dashboard and the storefront.
 *
 * Flat, JSON-friendly shape that maps 1-to-1 to a future backend table / REST payload.
 * All prices are integers in Algerian Dinar (DA).
 */
import { fold } from '../lib/format'
import { categories } from '../mockData'

export interface StoreProduct {
  id: string
  name: string
  /** Category id (see `categories` in mockData.ts). */
  category: string
  /** Regular price (DA). */
  price: number
  /** Whether the promotion is currently applied on the storefront. */
  hasDiscount: boolean
  /**
   * Promo price (DA). Kept even while `hasDiscount` is false so a promotion can be re-applied
   * in one click; only used when `hasDiscount` is true and the value is below `price`.
   */
  discountPrice: number | null
  /** Optional warranty label (\"12 mois\", free text…). Empty string = no warranty. */
  warranty: string
  description: string
  /** Up to MAX_IMAGES URLs / data-URL previews, main image first. */
  images: string[]
  inStock: boolean
  /** Shown in the storefront Hero / Slideshow when true. */
  isFeaturedHero: boolean
}

/** Everything but the id (the id is generated by the store on creation). */
export type ProductInput = Omit<StoreProduct, 'id'>

export const MAX_IMAGES = 5

/** Preset warranty durations offered by the form (custom text is also allowed). */
export const WARRANTY_PRESETS = ['6 mois', '12 mois', '24 mois'] as const

export const WARRANTY_NONE = 'none'
export const WARRANTY_CUSTOM = 'custom'

/** Maps a stored warranty string to the form selector value ('none' | preset | 'custom'). */
export function warrantyChoice(warranty: string): string {
  if (!warranty) return WARRANTY_NONE
  return (WARRANTY_PRESETS as readonly string[]).includes(warranty) ? warranty : WARRANTY_CUSTOM
}

export const toInput = (p: StoreProduct): ProductInput => ({
  name: p.name,
  category: p.category,
  price: p.price,
  hasDiscount: p.hasDiscount,
  discountPrice: p.discountPrice,
  warranty: p.warranty,
  description: p.description,
  images: [...p.images],
  inStock: p.inStock,
  isFeaturedHero: p.isFeaturedHero,
})

/** The promo price actually applied on the storefront, or null when there is no active promotion. */
export function activeDiscountPrice(p: Pick<StoreProduct, 'price' | 'hasDiscount' | 'discountPrice'>): number | null {
  const dp = p.discountPrice
  return p.hasDiscount && dp !== null && dp > 0 && dp < p.price ? dp : null
}

export const hasActiveDiscount = (p: Pick<StoreProduct, 'price' | 'hasDiscount' | 'discountPrice'>) =>
  activeDiscountPrice(p) !== null

/** Price the customer pays. */
export const currentPrice = (p: Pick<StoreProduct, 'price' | 'hasDiscount' | 'discountPrice'>) =>
  activeDiscountPrice(p) ?? p.price

/** Discount percentage (0 when the promo price is missing or not lower than the regular price). */
export function discountPct(price: number, discountPrice: number): number {
  if (!(price > 0) || !(discountPrice > 0) || discountPrice >= price) return 0
  return Math.round((1 - discountPrice / price) * 100)
}

/** Suggested promo price for a quick "-10 % / -20 %…" button: rounded to 50 DA, always below `price`. */
export function suggestPromoPrice(price: number, pct: number): number {
  const raw = price * (1 - pct / 100)
  const rounded = Math.round(raw / 50) * 50
  const value = rounded > 0 && rounded < price ? rounded : Math.floor(raw)
  return Math.max(1, value)
}

export function slugify(name: string): string {
  const slug = fold(name)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/g, '')
  return slug || 'produit'
}

export function uniqueId(name: string, taken: Set<string>): string {
  const base = slugify(name)
  if (!taken.has(base)) return base
  let n = 2
  while (taken.has(`${base}-${n}`)) n += 1
  return `${base}-${n}`
}

const asString = (v: unknown) => (typeof v === 'string' ? v : '')

/** Normalises a form payload so the store never holds an inconsistent record. */
export function normalizeInput(input: ProductInput): ProductInput {
  const price = Math.max(1, Math.round(Number(input.price) || 0))
  const rawDp = Math.round(Number(input.discountPrice) || 0)
  const discountPrice = rawDp > 0 ? rawDp : null
  const candidate = { price, hasDiscount: input.hasDiscount, discountPrice }
  return {
    name: input.name.trim(),
    category: categories.some((c) => c.id === input.category) ? input.category : categories[0].id,
    price,
    hasDiscount: hasActiveDiscount(candidate),
    discountPrice,
    warranty: input.warranty.trim(),
    description: input.description.trim(),
    images: input.images.map((s) => s.trim()).filter(Boolean).slice(0, MAX_IMAGES),
    inStock: input.inStock,
    isFeaturedHero: input.isFeaturedHero === true,
  }
}

/** Defensive parser for data coming from localStorage. Returns null for unusable records. */
export function sanitizeProduct(raw: unknown): StoreProduct | null {
  if (!raw || typeof raw !== 'object') return null
  const r = raw as Record<string, unknown>
  const id = asString(r.id).trim()
  const name = asString(r.name).trim()
  const price = Number(r.price)
  if (!id || !name || !Number.isFinite(price) || price <= 0) return null

  const rawCategory = asString(r.category)
  const category = categories.some((c) => c.id === rawCategory) ? rawCategory : categories[0].id
  const rawDp = Number(r.discountPrice)
  const discountPrice = Number.isFinite(rawDp) && rawDp > 0 ? Math.round(rawDp) : null
  const images = Array.isArray(r.images)
    ? r.images.filter((s): s is string => typeof s === 'string' && s.trim() !== '').slice(0, MAX_IMAGES)
    : []

  return {
    id,
    name,
    category,
    price: Math.round(price),
    hasDiscount: r.hasDiscount === true,
    discountPrice,
    warranty: asString(r.warranty).trim(),
    description: asString(r.description),
    images,
    inStock: r.inStock !== false,
    isFeaturedHero: r.isFeaturedHero === true,
  }
}
